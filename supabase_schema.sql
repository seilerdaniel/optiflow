-- ============================================================================
--  OPTIFLOW - Fase 7 : Migracion SQLite -> Supabase (PostgreSQL)
--  Fabrica "De Otro Tiempo"
-- ============================================================================
--
--  COMO USARLO
--  -----------
--  Opcion A (recomendada): Supabase Dashboard -> SQL Editor -> New query ->
--          pegar este archivo -> Run.
--  Opcion B: psql "$SUPABASE_DB_URL" -f supabase_schema.sql
--
--  El servidor (server/db.js) TAMBIEN lo aplica automaticamente en el primer
--  arranque si detecta que la base esta vacia, asi que ninguna de las dos es
--  obligatoria.
--
--  CONVENCIONES DE MIGRACION (importantes para no romper la logica)
--  ---------------------------------------------------------------
--  1. TODAS las fechas se guardan como TEXT en formato ISO-8601 UTC
--     ("2026-10-14T15:03:07.123Z"), igual que en SQLite. El codigo usa
--     substr(fecha,1,10) para comparar por dia y new Date(iso) en JS:
--     si se migraran a timestamptz, esas comparaciones se desfasarian.
--  2. Los 0/1 de SQLite pasan a SMALLINT (no a BOOLEAN), porque los mappers
--     (mapOT/mapSector/mapOperario) hacen `!!row.activo` y `!!'t' === true`
--     dejaria siempre true para cualquier valor.
--  3. Los ids pasan a BIGINT GENERATED BY DEFAULT AS IDENTITY para que
--     ... RETURNING id siga devolviendo el ultimo id insertado.
--  4. Los CHECK/UNIQUE/indices replican 1:1 los de server/db.js.
--
--  SEGURIDAD
--  ---------
--  La aplicacion se conecta con el rol `postgres` (cadena SUPABASE_DB_URL),
--  que es el unico que necesita acceso total. Se REVOCA el acceso directo a
--  `anon` y `authenticated` (el navegador NUNCA habla con la base: sólo habla
--  con nuestra API de Vercel). `usuarios` y `sesiones` ademas llevan RLS.
-- ============================================================================

