-- ---------------------------------------------------------------------------
-- 3bis. INTEGRIDAD DE ETAPAS ABIERTAS  (auditoria C-1 / C-2 / A-5)
--
--   Dos indices unicos PARCIALES sobre etapas en curso: aunque dos tablets
--   disparen el mismo fichaje al mismo tiempo, Postgres rechaza el duplicado
--   (SQLSTATE 23505) y la API lo traduce a un 409 entendible.
--     C-1: una OT no puede tener DOS etapas abiertas en el MISMO sector.
--     C-2: un operario no puede tener DOS etapas abiertas a la vez.
--
--   Si la base ya tiene datos con duplicados (el bug que permitia la
--   ausencia de indice), se cierran AUTOMATICAMENTE los duplicados mas
--   antiguos conservando la etapa mas reciente de cada grupo. Mismo criterio
--   que server/db.js (cerrarEtapasDuplicadas), para que el orden de
--   aplicacion (SQL a mano o arranque automatico) sea indistinto.
-- ---------------------------------------------------------------------------
do $dup$
declare
  ids bigint[];
begin
  select array_agg(id) into ids
    from (
      select id,
             row_number() over (partition by ot_id, sector_id
                                order by fecha_hora_inicio desc, id desc) rn_sector,
             row_number() over (partition by lower(operario_nombre)
                                order by fecha_hora_inicio desc, id desc) rn_operario
        from public.registros_tiempos
       where estado_etapa in ('En Proceso','Pausado')
    ) x
   where rn_sector > 1 or rn_operario > 1;

  if ids is not null and array_length(ids, 1) > 0 then
    update public.registros_tiempos r
       set estado_etapa     = 'Finalizado',
           fecha_hora_fin   = coalesce(r.fecha_hora_fin, r.fecha_hora_inicio),
           duracion_minutos = greatest(0, round((
             extract(epoch from (coalesce(r.fecha_hora_fin, r.fecha_hora_inicio)::timestamptz
                                 - r.fecha_hora_inicio::timestamptz))
             - coalesce(r.segundos_pausados, 0)) / 60.0, 2)),
           pausa_inicio     = NULL,
           observacion      = coalesce(r.observacion || ' · ', '')
                             || 'Cierre automático por migración de integridad (etapa abierta duplicada).',
           -- to_char inline: la función optiflow_ts_utc() se define recién en la
           -- sección 10 y este bloque puede correr antes en una base existente.
           fecha_actualizacion = to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
     where r.id = any(ids);

    update public.eventos_pausa
       set fin_pausa = to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
     where fin_pausa is null and registro_id = any(ids);

    raise notice 'Integridad: % etapa(s) abierta(s) duplicada(s) cerradas (se conservo la mas reciente)', array_length(ids, 1);
  end if;
end $dup$;

create unique index if not exists uq_reg_ot_sector_abierta
